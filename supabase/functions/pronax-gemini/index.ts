import { serve } from 'https://deno.land/std@0.168.0/http/server.ts'
import { createClient } from 'https://esm.sh/@supabase/supabase-js@2.39.0'

const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
}

serve(async (req) => {
  // Handle CORS preflight requests
  if (req.method === 'OPTIONS') {
    return new Response('ok', { headers: corsHeaders })
  }

  try {
    const url = new URL(req.url)
    const pathParts = url.pathname.split('/')
    const action = pathParts[pathParts.length - 1]

    console.log('AI Request:', action)

    const body = await req.json()
    const { task, data, model, request, metrics, recentVideos } = body

    // For creator-coach, call local LangGraph server directly
    if (action === 'creator-coach') {
      try {
        // Call local LangGraph server for dynamic AI execution
        const localLangGraphUrl = 'http://localhost:8000/api/generate';
        const apiResponse = await fetch(localLangGraphUrl, {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({
            request: request || data?.request,
            metrics: metrics || data?.metrics,
            recentVideos: recentVideos || data?.recentVideos,
            taskType: 'creator_coach',
          }),
        });

        if (!apiResponse.ok) {
          throw new Error(`Local LangGraph server error: ${apiResponse.status} ${apiResponse.statusText}`);
        }

        const apiData = await apiResponse.json();
        console.log('Local LangGraph response:', apiData);

        // Return the dynamic response from LangGraph directly
        return new Response(JSON.stringify(apiData), {
          headers: { ...corsHeaders, 'Content-Type': 'application/json' },
          status: 200,
        });
      } catch (apiError) {
        console.error('Error calling local LangGraph server:', apiError);

        // Return error - no fallback to mock responses
        return new Response(
          JSON.stringify({
            error: 'Local LangGraph server unavailable',
            message: apiError.message,
            suggestion: 'Ensure your local LangGraph server is running at http://localhost:8000'
          }),
          {
            headers: { ...corsHeaders, 'Content-Type': 'application/json' },
            status: 503,
          }
        );
      }
    }

    // For other actions, return error - they should be implemented with LangGraph
    return new Response(
      JSON.stringify({
        error: 'Action not implemented',
        message: `Action '${action}' is not yet configured for local LangGraph. Please implement it or use 'creator-coach' for now.`,
      }),
      {
        headers: { ...corsHeaders, 'Content-Type': 'application/json' },
        status: 501,
      }
    )
  } catch (error) {
    console.error('Error:', error)
    return new Response(
      JSON.stringify({ error: error.message }),
      {
        headers: { ...corsHeaders, 'Content-Type': 'application/json' },
        status: 500,
      }
    )
  }
})

// Note: All third-party API integrations (Gemini) and hardcoded mock responses have been removed.
// This Edge Function now exclusively routes to the local LangGraph server at http://localhost:8000
// for dynamic AI responses generated by your local LangGraph pipeline.

